// ── POST /v1/data-subject-requests ───────────────────────────────────────────
// Any authenticated user may submit a DSR for themselves (POPIA ss23-25).

const CreateDsrBody = z.object({
  requestType: z.enum(["access", "correction", "objection", "deletion"]),
  requestDetails: z.string().max(4000).optional(),
});

router.post(
  "/v1/data-subject-requests",
  requireSession,
  async (req, res): Promise<void> => {
    const tenantId = req.session!.tenantId;
    const userId = req.session!.userId;

    const idempotencyKey = req.headers["idempotency-key"];
    if (!idempotencyKey) {
      sendProblem(res, Problems.idempotencyKeyRequired());
      return;
    }

    const parsed = CreateDsrBody.safeParse(req.body);
    if (!parsed.success) {
      sendProblem(res, Problems.validationFailed(
        parsed.error.message,
        parsed.error.issues.map((i) => ({ field: i.path.join("."), code: i.code, message: i.message })),
      ));
      return;
    }

    const [dsr] = await withTenantContext(tenantId, (tx) =>
      tx
        .insert(dataSubjectRequestsTable)
        .values({ tenantId, userId, ...parsed.data })
        .returning(),
    );

    await writeAuditLog({
      tenantId,
      actorId: userId,
      actorType: "user",
      action: "dsr.submitted",
      targetType: "data_subject_request",
      targetId: dsr!.id,
      requestId: String(idempotencyKey),
      metadata: { requestType: parsed.data.requestType },
    });

    // For deletion requests: create a receipt notice for the data subject and
    // emit bheka.notice.issued.v1 so bheka-notify can deliver it.
    // Other DSR types (access, correction, objection) are handled by the IO manually.
    if (parsed.data.requestType === "deletion") {
      const [notice] = await withTenantContext(tenantId, (tx) =>
        tx.insert(transparencyNoticesTable).values({
          tenantId,
          userId,
          noticeType: "data_subject_request_response",
          title: "Data Erasure Request Received",
          body: `Your request to erase your personal data has been received (reference: ${dsr!.id}). We will process your request within 21 days as required by POPIA.`,
          language: "en",
        }).returning(),
      );

      await publishEvent({
        event_id: uuidv7(),
        schema_version: "bheka.notice.issued.v1",
        occurred_at: new Date().toISOString(),
        producer: "bheka-case",
        data: {
          notice_id: notice!.id,
          tenant_id: tenantId,
          user_id: userId,
          notice_type: "data_subject_request_response",
          language: "en",
          issued_at: new Date().toISOString(),
          delivery_channels: ["in_app"],
        },
      });
    }

    res.status(201).json({
      id: dsr!.id,
      userId: dsr!.userId,
      requestType: dsr!.requestType,
      status: dsr!.status,
      requestDetails: dsr!.requestDetails,
      createdAt: dsr!.createdAt,
    });
  },
);

