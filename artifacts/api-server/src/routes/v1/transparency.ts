// Transparency notices and data subject requests — 009_API_SURFACE section 11.
//
// Routes:
//   GET  /v1/transparency-notices                         — authenticated user's notices
//   GET  /v1/transparency-notices/:noticeId               — single notice
//   POST /v1/transparency-notices/:noticeId/acknowledge   — mark acknowledged_at
//   GET  /v1/data-subject-requests                        — IO sees all; user sees own
//   POST /v1/data-subject-requests                        — data subject submits request
//   GET  /v1/data-subject-requests/:dsrId                 — single DSR
//   PATCH /v1/data-subject-requests/:dsrId                — IO resolves/transitions
//
// Transparency notices are generated by other services (bheka-notify, bheka-case)
// reacting to tier activations, policy changes, and conclusions (CANON section 5,
// 018_NOTIFICATIONS_AND_TRANSPARENCY). The gateway exposes read + acknowledge only.
//
// Data subject requests are POPIA ss23-25 rights requests (access, correction,
// objection, deletion). Any authenticated user may submit for themselves.
// The Information Officer resolves requests via PATCH.

import { Router, type IRouter } from "express";
import { uuidv7 } from "uuidv7";
import { publishEvent } from "@workspace/nats-client";
import { z } from "zod";
import { and, eq, gt, inArray } from "drizzle-orm";
import {
  db,
  transparencyNoticesTable,
  dataSubjectRequestsTable,
  roleAssignmentsTable,
  rolesTable,
} from "@workspace/db";
import { withTenantContext } from "../../lib/tenant-context.js";
import { writeAuditLog } from "../../lib/audit-writer.js";
import { sendProblem, Problems } from "../../lib/problem.js";
import { requireSession } from "../../middleware/require-session.js";
import { requireRole } from "../../middleware/require-role.js";

// Returns true if the given user holds any elevated role within the tenant.
// "Elevated" here means: can see all notices / DSRs in the tenant, not just their own.
async function hasElevatedRole(userId: string, tenantId: string): Promise<boolean> {
  const assignments = await withTenantContext(tenantId, (tx) =>
    tx
      .select({ id: roleAssignmentsTable.id })
      .from(roleAssignmentsTable)
      .innerJoin(rolesTable, eq(roleAssignmentsTable.roleId, rolesTable.id))
      .where(
        and(
          eq(roleAssignmentsTable.userId, userId),
          eq(roleAssignmentsTable.tenantId, tenantId),
          eq(roleAssignmentsTable.active, true),
          inArray(rolesTable.name, ["popia_information_officer", "security_administrator"]),
        ),
      )
      .limit(1),
  );
  return assignments.length > 0;
}

const router: IRouter = Router();

// ── GET /v1/transparency-notices ─────────────────────────────────────────────
// Returns notices for the authenticated user.
// IO and security_administrator may see all notices for the tenant via ?all=true.

router.get(
  "/v1/transparency-notices",
  requireSession,
  async (req, res): Promise<void> => {
    const tenantId = req.session!.tenantId;
    const userId = req.session!.userId;
    const allTenant = req.query.all === "true";
    const rawLimit = Number(req.query.limit ?? 50);
    const limit = Math.min(Math.max(1, rawLimit), 200);
    const cursor = req.query.cursor as string | undefined;

    const canSeeAll =
      allTenant && (await hasElevatedRole(req.session!.userId, tenantId));

    const rows = await withTenantContext(tenantId, (tx) =>
      tx
        .select()
        .from(transparencyNoticesTable)
        .where(
          and(
            eq(transparencyNoticesTable.tenantId, tenantId),
            canSeeAll ? undefined : eq(transparencyNoticesTable.userId, userId),
            cursor ? gt(transparencyNoticesTable.id, cursor) : undefined,
          ),
        )
        .orderBy(transparencyNoticesTable.id)
        .limit(limit + 1),
    );

    const hasMore = rows.length > limit;
    const items = hasMore ? rows.slice(0, limit) : rows;
    const nextCursor = hasMore ? items[items.length - 1]!.id : null;

    res.json({
      items: items.map((n) => ({
        id: n.id,
        userId: n.userId,
        noticeType: n.noticeType,
        title: n.title,
        body: n.body,
        language: n.language,
        issuedAt: n.issuedAt,
        acknowledgedAt: n.acknowledgedAt,
        createdAt: n.createdAt,
      })),
      pageInfo: { nextCursor, hasMore },
    });
  },
);

// ── GET /v1/transparency-notices/:noticeId ───────────────────────────────────

router.get(
  "/v1/transparency-notices/:noticeId",
  requireSession,
  async (req, res): Promise<void> => {
    const tenantId = req.session!.tenantId;
    const userId = req.session!.userId;
    const noticeId = req.params.noticeId as string;

    const isElevated = await hasElevatedRole(userId, tenantId);

    const [notice] = await withTenantContext(tenantId, (tx) =>
      tx
        .select()
        .from(transparencyNoticesTable)
        .where(
          and(
            eq(transparencyNoticesTable.id, noticeId),
            eq(transparencyNoticesTable.tenantId, tenantId),
            isElevated ? undefined : eq(transparencyNoticesTable.userId, userId),
          ),
        )
        .limit(1),
    );

    if (!notice) {
      sendProblem(res, Problems.notFound());
      return;
    }

    res.json({
      id: notice.id,
      tenantId: notice.tenantId,
      userId: notice.userId,
      noticeType: notice.noticeType,
      title: notice.title,
      body: notice.body,
      language: notice.language,
      issuedAt: notice.issuedAt,
      acknowledgedAt: notice.acknowledgedAt,
      createdAt: notice.createdAt,
      updatedAt: notice.updatedAt,
    });
  },
);

// ── POST /v1/transparency-notices/:noticeId/acknowledge ──────────────────────
// Data subject acknowledges receipt. Idempotent: second call is a no-op.

router.post(
  "/v1/transparency-notices/:noticeId/acknowledge",
  requireSession,
  async (req, res): Promise<void> => {
    const tenantId = req.session!.tenantId;
    const userId = req.session!.userId;
    const noticeId = req.params.noticeId as string;

    const [notice] = await withTenantContext(tenantId, (tx) =>
      tx
        .select()
        .from(transparencyNoticesTable)
        .where(
          and(
            eq(transparencyNoticesTable.id, noticeId),
            eq(transparencyNoticesTable.tenantId, tenantId),
            eq(transparencyNoticesTable.userId, userId),
          ),
        )
        .limit(1),
    );

    if (!notice) {
      sendProblem(res, Problems.notFound());
      return;
    }

    // Idempotent: already acknowledged.
    if (notice.acknowledgedAt) {
      res.json({
        id: notice.id,
        acknowledgedAt: notice.acknowledgedAt,
      });
      return;
    }

    const now = new Date();
    const [updated] = await withTenantContext(tenantId, (tx) =>
      tx
        .update(transparencyNoticesTable)
        .set({ acknowledgedAt: now, updatedAt: now })
        .where(
          and(
            eq(transparencyNoticesTable.id, noticeId),
            eq(transparencyNoticesTable.tenantId, tenantId),
          ),
        )
        .returning({ id: transparencyNoticesTable.id, acknowledgedAt: transparencyNoticesTable.acknowledgedAt }),
    );

    res.json({
      id: updated!.id,
      acknowledgedAt: updated!.acknowledgedAt,
    });
  },
);

