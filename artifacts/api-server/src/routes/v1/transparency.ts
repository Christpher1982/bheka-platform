// ── PATCH /v1/data-subject-requests/:dsrId ───────────────────────────────────
// IO / security_administrator resolves or transitions a DSR.

const PatchDsrBody = z.object({
  status: z.enum(["in_progress", "completed", "rejected"]).optional(),
  resolutionNotes: z.string().max(4000).optional(),
});

router.patch(
  "/v1/data-subject-requests/:dsrId",
  requireSession,
  requireRole("popia_information_officer", "security_administrator"),
  async (req, res): Promise<void> => {
    const tenantId = req.session!.tenantId;
    const actorId = req.session!.userId;
    const dsrId = req.params.dsrId as string;

    const parsed = PatchDsrBody.safeParse(req.body);
    if (!parsed.success) {
      sendProblem(res, Problems.validationFailed(
        parsed.error.message,
        parsed.error.issues.map((i) => ({ field: i.path.join("."), code: i.code, message: i.message })),
      ));
      return;
    }

    if (Object.keys(parsed.data).length === 0) {
      sendProblem(res, Problems.validationFailed("Request body must contain at least one field to update"));
      return;
    }

    const now = new Date();
    const isTerminal = parsed.data.status === "completed" || parsed.data.status === "rejected";
    const extraFields = isTerminal
      ? { resolvedAt: now, resolvedByUserId: actorId }
      : {};

    const [updated] = await withTenantContext(tenantId, (tx) =>
      tx
        .update(dataSubjectRequestsTable)
        .set({ ...parsed.data, ...extraFields, updatedAt: now })
        .where(
          and(
            eq(dataSubjectRequestsTable.id, dsrId),
            eq(dataSubjectRequestsTable.tenantId, tenantId),
          ),
        )
        .returning(),
    );

    if (!updated) {
      sendProblem(res, Problems.notFound());
      return;
    }

    await writeAuditLog({
      tenantId,
      actorId,
      actorType: "user",
      action: "dsr.updated",
      targetType: "data_subject_request",
      targetId: dsrId,
      requestId: String(req.headers["x-request-id"] ?? ""),
      metadata: { status: updated.status, requestType: updated.requestType },
    });

    res.json({
      id: updated.id,
      userId: updated.userId,
      requestType: updated.requestType,
      status: updated.status,
      resolutionNotes: updated.resolutionNotes,
      resolvedAt: updated.resolvedAt,
      resolvedByUserId: updated.resolvedByUserId,
      updatedAt: updated.updatedAt,
    });
  },
);

export default router;
